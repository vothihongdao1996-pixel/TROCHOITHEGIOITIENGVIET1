// Helper to get questions for Arena by Mode
export function getQuestionsForArena(mode: ArenaMode, count: number = 10): ArenaQuestion[] {
  const shuffled = [...ALL_ARENA_QUESTIONS].sort(() => Math.random() - 0.5);

  if (mode === 'practice') {
    // 10 easy & medium questions
    return shuffled.slice(0, 10);
  } else if (mode === 'challenge') {
    // 10 mixed questions with challenge pace
    return shuffled.slice(0, 10);
  } else {
    // review: comprehensive 15 questions covering all 7 types
    return shuffled.slice(0, Math.min(15, ALL_ARENA_QUESTIONS.length));
  }
}
